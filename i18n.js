const LANG_KEY = "jagavre-lang";

function getLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === "id" || saved === "en") return saved;
  const param = new URLSearchParams(location.search).get("lang");
  if (param === "id" || param === "en") return param;
  return "id";
}

function applyLanguage(lang) {
  const dict = I18N[lang] || I18N.id;
  document.documentElement.lang = lang === "en" ? "en" : "id";
  document.title = dict.metaTitle;
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", dict.metaDescription);
  const ogTitle = document.querySelector('meta[property="og:title"]');
  const ogDesc = document.querySelector('meta[property="og:description"]');
  const ogLocale = document.querySelector('meta[property="og:locale"]');
  if (ogTitle) ogTitle.setAttribute("content", dict.metaTitle);
  if (ogDesc) ogDesc.setAttribute("content", dict.metaDescription);
  if (ogLocale) ogLocale.setAttribute("content", lang === "en" ? "en_US" : "id_ID");

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] != null) el.innerHTML = dict[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (dict[key] != null) el.setAttribute("aria-label", dict[key]);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.getAttribute("data-i18n-alt");
    if (dict[key] != null) el.setAttribute("alt", dict[key]);
  });

  const menu = document.querySelector(".menu-toggle");
  if (menu && menu.getAttribute("aria-expanded") !== "true") {
    menu.setAttribute("aria-label", dict.openNav);
  } else if (menu) {
    menu.setAttribute("aria-label", dict.closeNav);
  }

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.lang === lang);
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });

  localStorage.setItem(LANG_KEY, lang);
}

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(getLang());
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
  });
});
